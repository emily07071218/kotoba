// 主題詞 id 從 9,000,001 起(不會與 JMdict ent_seq 衝突)
const THEME_ID_BASE = 9_000_000

const existing = new Set(
  (vocabData as { word: string; reading: string }[]).map((v) => `${v.word}|${v.reading}`)
)

export const THEME_VOCAB: VocabEntry[] = THEMES.flatMap((theme) =>
  theme.words
    .filter(([word, reading]) => !existing.has(`${word}|${reading}`))
    .map(([word, reading, meaningZh], i) => ({
      id: THEME_ID_BASE + i + 1,
      word,
      reading,
      level: '生活' as const,
      meaningZh,
      pos: [] as string[],
      theme: theme.name
    }))
)

export const THEME_BY_NAME = new Map(THEMES.map((t) => [t.name, t]))
export const THEME_VOCAB_BY_ID = new Map(THEME_VOCAB.map((v) => [v.id, v]))
